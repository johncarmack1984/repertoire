cat > students/NOTES.md <<'EOF'
# International students by country of origin and country of study

**Who it's for.** Our client, Meridian Education Advisors, wants an interactive globe for the "Where students go" page of their website. Prospective students and their parents will land on it. The client's brief says it should "look impressive in 3D".

**Files.**

- `countries.csv`: the countries in the data, with an id, a name, and a representative point (WGS84) to draw each country's flows from.
- `flows.csv`: students enrolled in a degree program abroad in the 2025-26 academic year, by country of origin and country of study. Pairs with fewer than 500 students are left out.

**Source line we use.** Meridian Education Advisors, from national education ministry enrollment statistics, 2025-26.
EOF

