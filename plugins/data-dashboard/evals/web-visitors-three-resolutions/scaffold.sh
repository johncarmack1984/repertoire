#!/usr/bin/env bash
# Few's web marketing analysis situation (chapter 8) as CSVs, for an analyst who wants no alerts.
# Visitors run 6% to 31% above the prior year by month; November 9 and 10 fall about 30% under their
# weekday baselines, and 11:00 today falls 38% under its hourly baseline. The pleated skirt is viewed
# far more than it sells.
set -euo pipefail

mkdir -p web

cat > web/NOTES.md <<'EOF'
# Web traffic data

**Who it's for.** Me, the web marketing analyst. I use it at my desk on a 1920 by 1080 monitor to analyze our traffic, not to monitor it. It's an analysis screen, so I don't want alerts or red flags on it: I want to see the patterns and compare, and I'll decide what matters.

**As of.** 2:00 PM Pacific Standard Time, Friday, November 13, 2026 (2026-11-13T14:00:00-08:00). Today's hourly numbers cover the complete hours from midnight to 1:59 PM.

**What I compare against.**

- A month's average daily visitors against the same month a year earlier.
- A day's visitors this month against the average for the same weekday over the 13 weeks before it.
- An hour's visitors today against the average for the same hour on Fridays over the prior 13 weeks.

**Files.**

- `visitors_daily.csv`: visitors per day from November 1, 2025 through November 12, 2026.
- `visitors_prior_year_monthly.csv`: average daily visitors for each month from November 2024 through October 2025, the year before the daily file starts.
- `weekday_baseline.csv`: for each day this month, the average visitors on the same weekday over the 13 weeks before it.
- `today_hourly.csv`: visitors in each complete hour today.
- `hourly_baseline.csv`: average visitors in each hour on Fridays over the prior 13 weeks.
- `products.csv`: the top 10 products this month by revenue, with each one's share of this month's revenue and of this month's product page views.
- `referrers.csv`: the top 10 referring sites this month, with referrals, share of all 21,480 referrals this month, change in referrals since the same month last year, and average revenue per referral.
- `bought_together_not_shown_together.csv`: product pairs often bought together that our pages never show together, with the share of orders that include both.
- `shown_together_rarely_bought_together.csv`: product pairs our pages show together that people rarely buy together, with the same share.
EOF

